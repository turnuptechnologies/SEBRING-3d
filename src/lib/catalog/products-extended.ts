type Common = {
  slug: string
  sku: string
  mpn?: string
  name: string
  brand: BrandSlug
  sub: SubcategorySlug
  scales: Scale[]
  price: number
  was?: number
  stock: number
  released: string
  isNew?: boolean
  featured?: boolean
  preorder?: string
  attrs?: ProductAttributes
  tags: string[]
  summary: string
  description: string[]
  highlights: string[]
  specs: Spec[]
}

function base(c: Common): Omit<Product, "art" | "views"> {
  return {
    slug: c.slug,
    sku: c.sku,
    mpn: c.mpn,
    name: c.name,
    brand: c.brand,
    category: CATEGORY_OF[c.sub],
    subcategory: c.sub,
    scales: c.scales,
    price: c.price,
    compareAtPrice: c.was,
    stock: c.stock,
    releasedAt: c.released,
    isNew: c.isNew,
    isFeatured: c.featured,
    preorder: c.preorder ? { ships: c.preorder } : undefined,
    attributes: c.attrs,
    tags: c.tags,
    summary: c.summary,
    description: c.description,
    highlights: c.highlights,
    specs: c.specs,
  }
}

function car(c: Common & { body: CarBody; livery: Livery; vehicle: VehicleInfo }): Product {
  return { ...base(c), vehicle: c.vehicle, art: { kind: "car", body: c.body, livery: c.livery }, views: ["hero", "side", "rear", "top"] }
}

function part(c: Common & { art: Omit<PartArt, "kind">; fits: Product["fits"] }): Product {
  return { ...base(c), fits: c.fits, art: { kind: "part", ...c.art }, views: ["hero", "detail", "alt"] }
}

