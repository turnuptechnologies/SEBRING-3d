/** The company behind the store. Embed once, site-wide (e.g. in the root layout or home page). */
export function organizationJsonLd(): OrganizationJsonLd {
  const social = sameAs()
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": JSON_LD_IDS.organization,
    name: site.name,
    legalName: site.legalName,
    alternateName: site.shortName,
    url: absoluteUrl("/"),
    logo: { "@type": "ImageObject", url: LOGO_URL, width: 180, height: 180 },
    email: site.email,
    telephone: telephone(),
    address: postalAddress(),
    contactPoint: [
      {
        "@type": "ContactPoint",
        contactType: "customer service",
        telephone: telephone(),
        email: site.email,
        areaServed: site.address.country,
        availableLanguage: ["English"],
      },
    ],
    ...(social ? { sameAs: social } : {}),
  }
}

/** The website entity — feeds the site name shown in search results. Home page only. */
export function websiteJsonLd(): WebSiteJsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": JSON_LD_IDS.website,
    name: site.name,
    alternateName: site.shortName,
    url: absoluteUrl("/"),
    inLanguage: "en-US",
    publisher: { "@id": JSON_LD_IDS.organization },
  }
}

/**
 * The physical shop + raceway as a local business (HobbyShop, plus
 * SportsActivityLocation for the track). Uses the SAMPLE address and hours.
 * Embed on /raceway and /contact.
 */
export function storeJsonLd(): StoreJsonLd {
  const hours = openingHours()
  const range = priceRange()
  const social = sameAs()
  return {
    "@context": "https://schema.org",
    "@type": ["HobbyShop", "SportsActivityLocation"],
    "@id": JSON_LD_IDS.store,
    name: site.name,
    url: absoluteUrl("/raceway"),
    description: site.description,
    image: SOCIAL_IMAGE_URL,
    logo: LOGO_URL,
    telephone: telephone(),
    email: site.email,
    address: postalAddress(),
    hasMap: directionsHref(),
    ...(hours.length
      ? {
          openingHoursSpecification: hours.map((h) => ({
            "@type": "OpeningHoursSpecification" as const,
            dayOfWeek: h.days.map((d) => `https://schema.org/${WEEKDAYS[d]}` as SchemaEnum),
            opens: h.opens,
            closes: h.closes,
          })),
        }
      : {}),
    currenciesAccepted: commerce.currency,
    paymentAccepted: commerce.paymentMethods.join(", "),
    ...(range ? { priceRange: range } : {}),
    parentOrganization: { "@id": JSON_LD_IDS.organization },
    ...(social ? { sameAs: social } : {}),
  }
}

/** Product + Offer for a product page — price, sale price, stock, shipping and returns. */
export function productJsonLd(product: Product): ProductJsonLd {
  const url = absoluteUrl(productPath(product))
  const images = productImages(product).map((img) => absoluteUrl(img.src))
  const onSale = Boolean(product.compareAtPrice && product.compareAtPrice > product.price)
  return {
    "@context": "https://schema.org",
    "@type": "Product",
    "@id": `${url}#product`,
    name: fullName(product),
    description: product.summary,
    url,
    sku: product.sku,
    ...(product.mpn ? { mpn: product.mpn } : {}),
    // Omitted until the render pipeline has produced real photography.
    ...(images.length ? { image: images } : {}),
    brand: { "@type": "Brand", name: brandName(product.brand) },
    category: `${categoryLabel(product.category)} > ${subcategoryLabel(product.subcategory)}`,
    releaseDate: product.releasedAt,
    ...(product.specs.length
      ? { additionalProperty: product.specs.map((s) => ({ "@type": "PropertyValue" as const, name: s.label, value: s.value })) }
      : {}),
    offers: {
      "@type": "Offer",
      url,
      price: money(product.price),
      priceCurrency: commerce.currency,
      ...(onSale
        ? {
            priceSpecification: [
              { "@type": "UnitPriceSpecification" as const, price: money(product.price), priceCurrency: commerce.currency },
              {
                "@type": "UnitPriceSpecification" as const,
                price: money(product.compareAtPrice!),
                priceCurrency: commerce.currency,
                priceType: "https://schema.org/StrikethroughPrice" as SchemaEnum,
              },
            ],
          }
        : {}),
      availability: availability(product),
      itemCondition: "https://schema.org/NewCondition",
      seller: { "@id": JSON_LD_IDS.organization },
      shippingDetails: shippingDetails(product),
      hasMerchantReturnPolicy: {
        "@type": "MerchantReturnPolicy",
        applicableCountry: site.address.country,
        returnPolicyCategory: "https://schema.org/MerchantReturnFiniteReturnWindow",
        merchantReturnDays: commerce.returnWindowDays,
        returnMethod: "https://schema.org/ReturnByMail",
      },
    },
  }
}

/**
 * Ordered product list for collection, brand and search pages. Pass the
 * products in the order they are displayed and the page path (or URL).
 */
export function itemListJsonLd(list: readonly Product[], url: string): ItemListJsonLd {
  return {
    "@context": "https://schema.org",
    "@type": "ItemList",
    url: absoluteUrl(url),
    numberOfItems: list.length,
    itemListOrder: "https://schema.org/ItemListOrderAscending",
    itemListElement: list.map((p, i) => ({
      "@type": "ListItem",
      position: i + 1,
      url: absoluteUrl(productPath(p)),
      name: fullName(p),
    })),
  }
}
