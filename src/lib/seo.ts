/**
 * Structured data (schema.org JSON-LD) for search engines and AI crawlers.
 *
 * Every builder is pure and deterministic (no Date.now()), so pages that embed
 * them stay prerenderable. Embed with:
 *
 *   <script {...jsonLdScriptProps(productJsonLd(product))} />
 *
 * Business details come from `site` / `commerce` (SAMPLE data until launch).
 * We never emit ratings or reviews — the store has none to show yet.
 */

import { brandName, categoryLabel, productImages, products, subcategoryLabel } from "@/lib/catalog"
import type { Product } from "@/lib/catalog/types"
import { formatPrice } from "@/lib/format"
import { commerce, directionsHref, site } from "@/lib/site"

/* ---------------------------------------------------------------------------
 * URLs
 * ------------------------------------------------------------------------- */

/** Absolute URL on the production origin: absoluteUrl("/brands") → "https://…/brands". */
export function absoluteUrl(path = "/") {
  return new URL(path, site.url).toString()
}

/** Canonical product route (mirrors `productHref`, which lives in a client module). */
export const productPath = (p: Pick<Product, "slug">) => `/products/${p.slug}`

/** Stable node ids so the graph links Organization ⇄ Store ⇄ Products. */
export const JSON_LD_IDS = {
  organization: `${site.url}/#organization`,
  website: `${site.url}/#website`,
  store: `${site.url}/#store`,
} as const

/** Square brand logo (the generated apple-icon, 180 × 180 PNG). */
const LOGO_URL = absoluteUrl("/apple-icon")
/** Site-wide social card generated by src/app/opengraph-image.tsx. */
const SOCIAL_IMAGE_URL = absoluteUrl("/opengraph-image")

/* ---------------------------------------------------------------------------
 * Types — a deliberately small slice of schema.org, enough to type-check what
 * we emit without pulling in schema-dts.
 * ------------------------------------------------------------------------- */

type SchemaEnum = `https://schema.org/${string}`
type Ref = { "@id": string }

interface JsonLdNode {
  "@context": "https://schema.org"
  "@type": string | string[]
  "@id"?: string
}

export interface PostalAddressLd {
  "@type": "PostalAddress"
  streetAddress: string
  addressLocality: string
  addressRegion: string
  postalCode: string
  addressCountry: string
}

export interface ContactPointLd {
  "@type": "ContactPoint"
  contactType: string
  telephone: string
  email: string
  areaServed: string
  availableLanguage: string[]
}

export interface OpeningHoursSpecificationLd {
  "@type": "OpeningHoursSpecification"
  dayOfWeek: SchemaEnum[]
  opens: string
  closes: string
}

export interface OrganizationJsonLd extends JsonLdNode {
  "@type": "Organization"
  "@id": string
  name: string
  legalName: string
  alternateName: string
  url: string
  logo: { "@type": "ImageObject"; url: string; width: number; height: number }
  email: string
  telephone: string
  address: PostalAddressLd
  contactPoint: ContactPointLd[]
  sameAs?: string[]
}

export interface WebSiteJsonLd extends JsonLdNode {
  "@type": "WebSite"
  "@id": string
  name: string
  alternateName: string
  url: string
  inLanguage: string
  publisher: Ref
}

export interface StoreJsonLd extends JsonLdNode {
  "@type": string[]
  "@id": string
  name: string
  url: string
  description: string
  image: string
  logo: string
  telephone: string
  email: string
  address: PostalAddressLd
  hasMap: string
  openingHoursSpecification?: OpeningHoursSpecificationLd[]
  currenciesAccepted: string
  paymentAccepted: string
  priceRange?: string
  parentOrganization: Ref
  sameAs?: string[]
}

export interface PriceSpecificationLd {
  "@type": "UnitPriceSpecification"
  price: string
  priceCurrency: string
  priceType?: SchemaEnum
}

export interface OfferLd {
  "@type": "Offer"
  url: string
  price: string
  priceCurrency: string
  priceSpecification?: PriceSpecificationLd[]
  availability: SchemaEnum
  itemCondition: SchemaEnum
  seller: Ref
  shippingDetails?: {
    "@type": "OfferShippingDetails"
    shippingRate: { "@type": "MonetaryAmount"; value: number; currency: string }
    shippingDestination: { "@type": "DefinedRegion"; addressCountry: string }
    deliveryTime?: {
      "@type": "ShippingDeliveryTime"
      handlingTime?: QuantitativeValueLd
      transitTime: QuantitativeValueLd
    }
  }
  hasMerchantReturnPolicy: {
    "@type": "MerchantReturnPolicy"
    applicableCountry: string
    returnPolicyCategory: SchemaEnum
    merchantReturnDays: number
    returnMethod: SchemaEnum
  }
}

interface QuantitativeValueLd {
  "@type": "QuantitativeValue"
  minValue: number
  maxValue: number
  unitCode: "DAY"
}

export interface ProductJsonLd extends JsonLdNode {
  "@type": "Product"
  "@id": string
  name: string
  description: string
  url: string
  sku: string
  mpn?: string
  image?: string[]
  brand: { "@type": "Brand"; name: string }
  category: string
  releaseDate: string
  additionalProperty?: { "@type": "PropertyValue"; name: string; value: string }[]
  offers: OfferLd
}

export interface ItemListJsonLd extends JsonLdNode {
  "@type": "ItemList"
  url: string
  numberOfItems: number
  itemListOrder: SchemaEnum
  itemListElement: { "@type": "ListItem"; position: number; url: string; name: string }[]
}

export type AnyJsonLd = OrganizationJsonLd | WebSiteJsonLd | StoreJsonLd | ProductJsonLd | ItemListJsonLd

/* ---------------------------------------------------------------------------
 * Serialisation
 * ------------------------------------------------------------------------- */

/**
 * JSON for a <script type="application/ld+json">. Escapes the characters that
 * could close the tag or break parsing (per the Next.js JSON-LD guide).
 */
export function serializeJsonLd(data: AnyJsonLd | AnyJsonLd[] | Record<string, unknown>) {
  // Line/paragraph separators via replaceAll: in a regex literal the compiler
  // emits them raw, which is a syntax error.
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .replaceAll(String.fromCharCode(0x2028), "\\u2028")
    .replaceAll(String.fromCharCode(0x2029), "\\u2029")
}

/** Spread onto a native <script> element (not next/script — JSON-LD is data, not code). */
export function jsonLdScriptProps(data: AnyJsonLd | AnyJsonLd[] | Record<string, unknown>) {
  return { type: "application/ld+json", dangerouslySetInnerHTML: { __html: serializeJsonLd(data) } } as const
}

/* ---------------------------------------------------------------------------
 * Opening hours — parses the human-readable `site.hours` rows ("Wed – Thu",
 * "3:00 pm – 9:00 pm"). Rows that cannot be parsed are skipped rather than
 * guessed, so a typo in the config never publishes wrong hours.
 * ------------------------------------------------------------------------- */

export const WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"] as const
export type Weekday = (typeof WEEKDAYS)[number]

export interface OpeningHours {
  /** Day indexes, 0 = Monday … 6 = Sunday. */
  days: number[]
  /** 24-hour "HH:MM", local store time. */
  opens: string
  /** 24-hour "HH:MM"; earlier than `opens` when the session runs past midnight. */
  closes: string
  /** The original row, for display. */
  label: string
  hours: string
  note?: string
}

const pad2 = (n: number) => String(n).padStart(2, "0")

/** "Wed" · "wednesday" · "Tu" → 2 · 2 · 1; -1 when unknown. */
function dayIndex(token: string) {
  const t = token.trim().toLowerCase().replace(/\.$/, "")
  if (t.length < 2) return -1
  return WEEKDAYS.findIndex((d) => d.toLowerCase().startsWith(t.slice(0, 3)))
}

/** "Mon – Tue" · "Friday" · "Mon, Wed & Fri" · "Sat to Sun" → [0, 1] … ; null when unparseable. */
export function parseDays(label: string): number[] | null {
  const out = new Set<number>()
  for (const segment of label.split(/\s*(?:,|&|\band\b)\s*/i).filter(Boolean)) {
    const ends = segment.split(/\s*(?:[–—-]|\bto\b|\bthrough\b|\bthru\b)\s*/i).filter(Boolean)
    if (ends.length === 1) {
      const d = dayIndex(ends[0])
      if (d < 0) return null
      out.add(d)
    } else if (ends.length === 2) {
      const a = dayIndex(ends[0])
      const b = dayIndex(ends[1])
      if (a < 0 || b < 0) return null
      for (let i = a; ; i = (i + 1) % 7) {
        out.add(i)
        if (i === b) break
      }
    } else {
      return null
    }
  }
  return out.size ? [...out].sort((x, y) => x - y) : null
}

/** "3:00 pm" · "3 pm" · "15:00" · "noon" · "midnight" → "15:00"; null when unparseable. */
export function parseClock(value: string): string | null {
  const t = value.trim().toLowerCase().replace(/\./g, "")
  if (t === "noon") return "12:00"
  if (t === "midnight") return "00:00"
  const m = t.match(/^(\d{1,2})(?::(\d{2}))?\s*(am|pm)?$/)
  if (!m) return null
  let h = Number(m[1])
  const min = m[2] ? Number(m[2]) : 0
  if (min > 59) return null
  if (m[3]) {
    if (h < 1 || h > 12) return null
    h = (h % 12) + (m[3] === "pm" ? 12 : 0)
  } else if (h > 23) {
    return null
  }
  return `${pad2(h)}:${pad2(min)}`
}

/** Open sessions from `site.hours` (closed rows omitted). */
export function openingHours(rows: readonly { days: string; hours: string; note?: string }[] = site.hours): OpeningHours[] {
  const out: OpeningHours[] = []
  for (const row of rows) {
    if (/closed/i.test(row.hours)) continue
    const days = parseDays(row.days)
    const [from, to, ...rest] = row.hours.split(/\s*(?:[–—-]|\bto\b)\s*/i)
    const opens = from ? parseClock(from) : null
    const closes = to ? parseClock(to) : null
    if (!days || !opens || !closes || rest.length) continue
    out.push({ days, opens, closes, label: row.days, hours: row.hours, note: row.note })
  }
  return out
}

