function postalAddress(): PostalAddressLd {
  const a = site.address
  return {
    "@type": "PostalAddress",
    streetAddress: a.street,
    addressLocality: a.city,
    addressRegion: a.region,
    postalCode: a.postalCode,
    addressCountry: a.country,
  }
}

/** "+15550121212" from the configured tel: link. */
const telephone = () => site.phoneHref.replace(/^tel:/, "")

/**
 * Social profiles worth publishing as `sameAs`. Bare network homepages (the
 * SAMPLE placeholders, e.g. "https://instagram.com/") are not profiles, so
 * they are left out until real handles are configured.
 */
function sameAs(): string[] | undefined {
  const urls = site.social
    .map((s) => s.href as string)
    .filter((href) => {
      if (!href) return false
      try {
        return new URL(href).pathname.replace(/\/+$/, "") !== ""
      } catch {
        return false
      }
    })
  return urls.length ? urls : undefined
}

const fullName = (p: Product) => `${brandName(p.brand)} ${p.name}`
const money = (n: number) => n.toFixed(2)

function priceRange(): string | undefined {
  if (!products.length) return undefined
  const prices = products.map((p) => p.price)
  return `${formatPrice(Math.min(...prices), { round: true })}–${formatPrice(Math.max(...prices), { round: true })}`
}

function availability(p: Product): SchemaEnum {
  if (p.preorder) return "https://schema.org/PreOrder"
  return p.stock > 0 ? "https://schema.org/InStock" : "https://schema.org/OutOfStock"
}

/** Business days in transit parsed from the standard rate's ETA ("3–5 business days"). */
function transitDays(): { min: number; max: number } | null {
  const m = commerce.shippingRates.standard.eta.match(/(\d+)\s*(?:[–—-]|to)\s*(\d+)/)
  return m ? { min: Number(m[1]), max: Number(m[2]) } : null
}

const dayRange = (minValue: number, maxValue: number): QuantitativeValueLd => ({ "@type": "QuantitativeValue", minValue, maxValue, unitCode: "DAY" })

function shippingDetails(p: Product): OfferLd["shippingDetails"] {
  const standard = commerce.shippingRates.standard
  const transit = transitDays()
  const sameDay = /same (business )?day/i.test(commerce.processing)
  return {
    "@type": "OfferShippingDetails",
    shippingRate: { "@type": "MonetaryAmount", value: p.price >= commerce.freeShippingThreshold ? 0 : standard.price, currency: commerce.currency },
    shippingDestination: { "@type": "DefinedRegion", addressCountry: site.address.country },
    ...(transit
      ? {
          deliveryTime: {
            "@type": "ShippingDeliveryTime" as const,
            ...(sameDay ? { handlingTime: dayRange(0, 1) } : {}),
            transitTime: dayRange(transit.min, transit.max),
          },
        }
      : {}),
  }
}

